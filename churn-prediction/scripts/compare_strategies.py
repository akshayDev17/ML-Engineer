"""Ablation study: re-run the same pipeline with one component swapped at a time.

    python scripts/compare_strategies.py            # writes notes/results/ablation.md

Uses fixed hyper-parameters (no Optuna) so that differences come from the swapped component,
and a separate artifacts directory so the real model registry isn't polluted.
"""
from __future__ import annotations

import logging
from dataclasses import replace

import numpy as np
from sklearn.metrics import average_precision_score, roc_auc_score

from churn.cli import DEFAULT_CONFIG, PROJECT_ROOT
from churn.config import (FeatureSelectionConfig, ImbalanceConfig, PipelineConfig, RunArgs, ThresholdConfig,
                          TuningConfig)
from churn.data.generators import PatternChurnDataGenerator
from churn.factory import build_components
from churn.pipeline import ChurnPipeline

logging.getLogger().setLevel(logging.WARNING)
ARGS = RunArgs(n_rows=20_000, imbalance_ratio=9.0)


def base_config() -> PipelineConfig:
    cfg = PipelineConfig.from_yaml(DEFAULT_CONFIG)
    return replace(cfg, tuning=TuningConfig("fixed"),
                   paths=replace(cfg.paths, artifacts_dir="artifacts/ablations", data_dir="artifacts/ablations/data"))


def run(cfg: PipelineConfig) -> dict:
    logging.getLogger().setLevel(logging.WARNING)
    result = ChurnPipeline(cfg, build_components(cfg, PROJECT_ROOT)).run(ARGS)
    r = result.test_report
    return {"features": len(result.selection.selected), "precision": r.precision, "recall": r.recall, "f1": r.f1,
            "roc_auc": r.roc_auc, "pr_auc": r.pr_auc, "threshold": r.threshold}


def oracle_ceiling(cfg: PipelineConfig) -> dict:
    """Score the clean data with the generator's TRUE churn probabilities: the best any model can do."""
    gen = PatternChurnDataGenerator(cfg.data.snapshot_date, cfg.seed)
    rng = np.random.default_rng(cfg.seed)
    feats = gen._sample_features(rng, ARGS.n_rows)
    proba = gen._churn_probability(feats, ARGS.positive_rate, rng)
    y = rng.binomial(1, proba)
    return {"roc_auc": roc_auc_score(y, proba), "pr_auc": average_precision_score(y, proba)}


def table(title: str, rows: dict[str, dict]) -> str:
    out = [f"### {title}", "", "| variant | #features | precision | recall | F1 | ROC-AUC | PR-AUC | threshold |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for name, m in rows.items():
        out.append(f"| {name} | {m['features']} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | "
                   f"{m['roc_auc']:.3f} | {m['pr_auc']:.3f} | {m['threshold']:.3f} |")
    return "\n".join(out) + "\n"


def main() -> None:
    cfg = base_config()
    sel = cfg.feature_selection.params
    selection_rows = {
        "hybrid: hygiene -> permutation (default)": run(cfg),
        "hygiene only (all clean features)": run(replace(cfg, feature_selection=FeatureSelectionConfig("hygiene", sel))),
        "hygiene -> mutual information": run(replace(cfg, feature_selection=FeatureSelectionConfig(
            "mutual_info", {**sel, "mutual_info": {"min_mi": 0.001}}))),
        "permutation only (NO hygiene: leak allowed)": run(replace(cfg, feature_selection=FeatureSelectionConfig(
            "permutation", sel))),
    }
    imbalance_rows = {}
    for name, params in [("none", {}), ("class_weight", {"power": 1.0}), ("class_weight", {"power": 0.5}),
                         ("weighted_sampler", {}), ("smotenc", {"sampling_strategy": 0.5}),
                         ("random_undersample", {"sampling_strategy": 0.5})]:
        label = name + (f" (power={params['power']})" if "power" in params else "")
        imbalance_rows[label] = run(replace(cfg, imbalance=ImbalanceConfig(name, params)))
    threshold_rows = {
        "class_weight @ fixed 0.5": run(replace(cfg, threshold=ThresholdConfig("fixed", {"value": 0.5}))),
        "class_weight @ max F1 on val": run(cfg),
        "class_weight @ max F2 on val": run(replace(cfg, threshold=ThresholdConfig("max_fbeta", {"beta": 2.0}))),
        "class_weight @ recall>=0.8 on val": run(replace(cfg, threshold=ThresholdConfig("min_recall",
                                                                                      {"target_recall": 0.8}))),
    }
    oracle = oracle_ceiling(cfg)
    report = "\n".join([
        "# Ablation results", "",
        f"Generated by `scripts/compare_strategies.py` — {ARGS.n_rows} rows, imbalance ratio {ARGS.imbalance_ratio:g}, "
        "pattern generator, fixed hyper-parameters (MLP 64-32), seed 42. All metrics on the held-out TEST split.", "",
        f"**Oracle ceiling** (the generator's true probabilities on clean data): ROC-AUC {oracle['roc_auc']:.3f}, "
        f"PR-AUC {oracle['pr_auc']:.3f}. No model can systematically beat this.", "",
        table("Feature selection (imbalance = class_weight, threshold = max F1)", selection_rows),
        table("Imbalance strategy (selection = hybrid, threshold = max F1 on val)", imbalance_rows),
        table("Threshold policy (selection = hybrid, imbalance = class_weight)", threshold_rows),
    ])
    out = PROJECT_ROOT / "notes" / "results" / "ablation.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
